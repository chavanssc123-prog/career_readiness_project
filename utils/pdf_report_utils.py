import io
from datetime import datetime
from typing import Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    Paragraph,
    PageBreak,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def _build_paragraph(text: str, style_name: str = "Normal") -> Paragraph:
    styles = getSampleStyleSheet()
    return Paragraph(text, styles[style_name])


def _build_table(data: List[List[str]], col_widths: Optional[List[int]] = None) -> Table:
    styled_rows = []
    styles = getSampleStyleSheet()
    body_style = styles["BodyText"]
    for row in data:
        styled_row = [Paragraph(str(cell), body_style) for cell in row]
        styled_rows.append(styled_row)

    table = Table(styled_rows, colWidths=col_widths or [2.5 * inch] * len(data[0]))
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0B5394")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CCCCCC")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    return table


def _format_list(items: List[str]) -> str:
    if not items:
        return "None"
    return "<br/>".join([item for item in items])


def generate_career_report_pdf(
    user: Dict,
    profile: Dict,
    resume_data: Dict,
    career_prediction: Dict,
    skill_gap: Dict,
    roadmap: Dict,
    analytics_summary: Dict,
) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=72, leftMargin=72, topMargin=72, bottomMargin=72)
    elements = []
    styles = getSampleStyleSheet()
    normal_style = styles["Normal"]
    heading_style = ParagraphStyle(
        "Heading1",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=colors.HexColor("#0B5394"),
    )
    subheading_style = ParagraphStyle(
        "Heading2",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#0B5394"),
    )

    # Cover Page
    elements.append(Paragraph("Career Readiness & Skill Gap Report", heading_style))
    elements.append(Spacer(1, 0.3 * inch))
    elements.append(Paragraph(f"Candidate: {user.get('name', 'N/A')}", normal_style))
    elements.append(Paragraph(f"Email: {user.get('email', 'N/A')}", normal_style))
    elements.append(Paragraph(f"Report Date: {datetime.now().strftime('%Y-%m-%d')}", normal_style))
    elements.append(Spacer(1, 0.5 * inch))
    elements.append(Paragraph("This report provides a consolidated view of your profile readiness, resume analysis, career recommendation, skill gap assessment, and personalized roadmap.", normal_style))
    elements.append(Spacer(1, 0.5 * inch))
    elements.append(Paragraph("Generated by AI Career Readiness & Skill Gap Analyzer", normal_style))
    elements.append(PageBreak())

    # Profile Summary
    elements.append(Paragraph("Profile Summary", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    profile_table_data = [
        ["CGPA", str(profile.get("cgpa", "N/A"))],
        ["Communication", str(profile.get("communication", "N/A"))],
        ["Logical Reasoning", str(profile.get("logical_reasoning", "N/A"))],
        ["Projects Count", str(profile.get("projects_count", "N/A"))],
        ["Certifications Count", str(profile.get("certifications_count", "N/A"))],
        ["Internship Count", str(profile.get("internship_count", "N/A"))],
        ["Interest Domain", profile.get("interest_domain", "N/A")],
    ]
    elements.append(_build_table(profile_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Resume Analysis
    elements.append(Paragraph("Resume Analysis", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    resume_table_data = [
        ["Resume Uploaded", "Yes" if resume_data else "No"],
        ["Skills Extracted", resume_data.get("skills", "None")],
        ["Projects Extracted", resume_data.get("projects", "None")],
        ["Certifications Extracted", resume_data.get("certifications", "None")],
        ["Education Extracted", resume_data.get("education", "None")],
    ]
    elements.append(_build_table(resume_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Career Recommendation
    elements.append(Paragraph("Career Recommendation", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    selected_career = career_prediction.get("selected_role") or career_prediction.get("recommended_role")
    selection_type = "AI Recommended" if career_prediction.get("selected_role") == career_prediction.get("predicted_role") else "User Selected"
    recommendation_table_data = [
        ["AI Recommended Career", career_prediction.get("recommended_role", "N/A")],
        ["Confidence Score", f"{career_prediction.get('confidence_score', 0.0):.1f}%"],
        ["Final Selected Career", selected_career],
        ["Career Selection Type", selection_type],
        ["Career Category", analytics_summary.get("career_category", "N/A")],
    ]
    elements.append(_build_table(recommendation_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Skill Gap Analysis
    elements.append(Paragraph("Skill Gap Analysis", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    matched_skills = _format_list(str(skill_gap.get("matched_skills", "")).split(", "))
    missing_skills = _format_list(str(skill_gap.get("missing_skills", "")).split(", "))
    extra_skills = _format_list(str(skill_gap.get("extra_skills", "")).split(", "))
    skill_gap_table_data = [
        ["Matched Skills", matched_skills],
        ["Missing Skills", missing_skills],
        ["Extra Skills", extra_skills],
        ["Skill Match Score", f"{skill_gap.get('skill_match_score', 0.0):.1f}%"],
        ["Readiness Score", f"{skill_gap.get('readiness_score', 0.0):.1f}%"],
    ]
    elements.append(_build_table(skill_gap_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Personalized Roadmap
    elements.append(Paragraph("Personalized Roadmap", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    roadmap_table_data = [
        ["Career Role", roadmap.get("career_role", "N/A")],
        ["Duration", f"{roadmap.get('duration_months', 0)} months"],
        ["Readiness Score", f"{roadmap.get('readiness_score', 0.0):.1f}%"],
        ["Roadmap Summary", _format_list(roadmap.get("roadmap_text", "").split("\n"))],
    ]
    elements.append(_build_table(roadmap_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Recommended Projects and Certifications
    elements.append(Paragraph("Recommended Projects", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    elements.append(Paragraph(_format_list(analytics_summary.get("projects", [])), normal_style))
    elements.append(Spacer(1, 0.2 * inch))
    elements.append(Paragraph("Recommended Certifications", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    elements.append(Paragraph(_format_list(analytics_summary.get("certifications", [])), normal_style))
    elements.append(Spacer(1, 0.2 * inch))

    # Career Selection Summary
    elements.append(Paragraph("Career Selection Details", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    selection_table_data = [
        ["AI Recommended Career", career_prediction.get("recommended_role", "N/A")],
        ["Confidence Score", f"{career_prediction.get('confidence_score', 0.0):.1f}%"],
        ["Final Selected Career", selected_career],
        ["Career Selection Type", selection_type],
    ]
    elements.append(_build_table(selection_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Analytics Summary
    elements.append(Paragraph("Analytics Summary", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    summary_table_data = [
        ["Profile Completion", f"{analytics_summary.get('profile_completion', 0.0):.1f}%"],
        ["Resume ATS Score", f"{analytics_summary.get('ats_score', 0.0):.1f}%"],
        ["Skill Match Score", f"{analytics_summary.get('skill_match_score', 0.0):.1f}%"],
        ["Roadmap Readiness", f"{analytics_summary.get('roadmap_progress', 0.0):.1f}%"],
        ["Overall Readiness", f"{analytics_summary.get('overall_readiness', 0.0):.1f}%"],
    ]
    elements.append(_build_table(summary_table_data, col_widths=[2.5 * inch, 3.5 * inch]))
    elements.append(Spacer(1, 0.2 * inch))

    # Final Conclusion
    elements.append(Paragraph("Final Conclusion", subheading_style))
    elements.append(Spacer(1, 0.1 * inch))
    conclusion_text = (
        "This report summarizes your current career readiness and identifies key development areas. "
        "Use the recommendation and roadmap sections to prioritize targeted growth and strengthen your profile." 
    )
    elements.append(Paragraph(conclusion_text, normal_style))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
